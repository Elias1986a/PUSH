import AppKit
import PUSHCore

/// What the user last copied, and when — for the prompt's "Copied:" line
/// (`ClipboardPolicy` decides whether it is used). Read only at the moment
/// of a suggestion; never stored, never logged.
@MainActor
final class ClipboardContext {
    static let shared = ClipboardContext()

    /// Anything already on the clipboard when Type started is not counted as
    /// a fresh copy.
    private var lastCount = NSPasteboard.general.changeCount
    private var copiedAt: Date?
    private var timer: Timer?

    /// Password managers mark what they copy (nspasteboard.org conventions).
    private static let hidden: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    /// Checks the change count each second: macOS sends no notification, and
    /// the time of the copy is what freshness is measured from.
    func start() {
        guard timer == nil else { return }
        lastCount = NSPasteboard.general.changeCount
        copiedAt = nil
        timer = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardContext.shared.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        copiedAt = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastCount else { return }
        lastCount = pasteboard.changeCount
        let concealed = !(Set(pasteboard.types ?? []).isDisjoint(with: Self.hidden))
        copiedAt = concealed ? nil : Date()
    }

    /// The copy, when it is fresh and relevant to `before`.
    func text(for before: String) -> String? {
        guard let copiedAt, let string = NSPasteboard.general.string(forType: .string) else { return nil }
        return ClipboardPolicy.select(string, copiedAt: copiedAt, before: before)
    }
}
